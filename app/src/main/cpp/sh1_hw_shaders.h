/* sh1_hw_shaders.h — v9.9 hardware-backend shader sources.
 *
 * The mesh fragment shader is the v9.8 desktop-PoC shader (proven:
 * PSNR 43.85..50.26 dB, 98.94..99.20% bit-exact vs the software
 * rasterizer; jitter bit-exact by construction + the 200k GPU sweep)
 * restructured for the v9.9 ANDROID architecture:
 *   - INSTANCED rendering (per-triangle DDA parameters become instance
 *     attributes instead of per-draw uniforms) — one draw per pass;
 *   - a GL_TEXTURE_2D_ARRAY holding every Scene texture (manual wrap
 *     in-shader; the shader never relies on GL wrap modes);
 *   - MRT: attachment 0 = RGBA8 color, attachment 1 = R32F z (the
 *     flake-occlusion depth raster_tri writes for OPAQUE non-hole
 *     fragments: `if (pass == RP_OPAQUE) fb->z[pi] = z`).
 *
 * The SWANSTATION-VERBATIM block (s_dither_values + ApplyDithering,
 * gpu_hw_shadergen.cpp's fragment emission, with shadergen's own
 * WriteHeader ambient macros) is carried over CHARACTER-FOR-CHARACTER
 * from the v9.8 PoC. The DuckStation UV DDA block (mul_u32 /
 * shr_s64_12 / add64 + the Q24 evaluation) is carried over VERBATIM;
 * v45 audit H-1 changed ONLY the anchor step (dxq/dyq): the KX/KY
 * slots now carry FLOAT BITS and the multiply runs in float, keeping
 * raster_tri's double-precision factor through the DDA (the old int
 * pre-truncation drifted up to 0.08 engine px at fractional scales).
 *
 * The PERSP (modern/--modern wobble-off) path: gl_Position.w carries
 * the view depth; UV varyings then interpolate perspective-correctly
 * (the engine's persp branch) while col/ocol/z are recovered AFFINE
 * (the engine interpolates them with screen-space barycentrics in BOTH
 * modes) via the (attr*w, w) varying pair — attr_affine = attrw * w_fs.
 * In PS1 mode w == 1 and every varying is affine directly.
 *
 * Vulkan flavor: hw_mesh_vk.vert / hw_mesh_vk.frag are compiled to
 * SPIR-V offline by glslang (the same toolchain Swanstation's pre-baked
 * embedded_spirv pipeline uses); their logic blocks are copied
 * IDENTICALLY from this file (dither block verbatim-Swanstation, DDA
 * block verbatim-v9.8) — the harness comparison proves the two flavors
 * compute the same pixels. Vulkan differences only: y-down NDC origin
 * (no flip), gl_FragCoord directly top-left, push constants.
 */
#ifndef SH1_HW_SHADERS_H
#define SH1_HW_SHADERS_H

/* ============================ VERTEX SHADER (GLES) ==================== */
/* attributes: 0-4 vertex rate, 5-9 instance rate (see sh1_hw_render.c) */
static const char* HW_VS_MESH_GLES = (
    "#version 300 es\n"
    "precision highp float;\n"
    "precision highp int;\n"
    "layout(location = 0) in vec2 a_pos;    /* GTE-SNAPPED screen x,y (top-left) */\n"
    "layout(location = 1) in vec2 a_uv;     /* normalized glTF UVs               */\n"
    "layout(location = 2) in vec3 a_col;    /* per-vertex fog/light color        */\n"
    "layout(location = 3) in vec3 a_ocol;   /* per-vertex additive veil color    */\n"
    "layout(location = 4) in float a_z;     /* view depth (m)                    */\n"
    "layout(location = 5) in uvec4 a_ddaA;      /* U0,V0,Dudx,Dudy (u32 Q24)     */\n"
    "layout(location = 6) in uvec2 a_ddaB;      /* Dvdx,Dvdy (u32 Q24)           */\n"
    "layout(location = 7) in ivec4 a_ddaAnchor; /* X0,Y0 (Q12), KX,KY (float bits)  */\n"
    "layout(location = 8) in ivec2 a_texSize;   /* tw,th                        */\n"
    "layout(location = 9) in ivec4 a_flags;     /* mode,useDDA,persp,layer      */\n"
    "uniform vec2 u_fbSize;\n"
    "out vec2 v_uv;\n"
    "out vec3 v_colw;\n"
    "out vec3 v_ocolw;\n"
    "out float v_zw;\n"
    "out float v_w;\n"
    "flat out uvec4 v_ddaA;\n"
    "flat out uvec2 v_ddaB;\n"
    "flat out ivec4 v_ddaAnchor;\n"
    "flat out ivec2 v_texSize;\n"
    "flat out ivec4 v_flags;\n"
    "void main() {\n"
    "  /* screen(top-left) -> NDC(bottom-left). No Swanstation vertex_offset:\n"
    "   * that +0.5 compensates DuckStation's INTEGER-position SW sampling; our\n"
    "   * SW rasterizer samples pixel CENTERS (px = x + 0.5) exactly like GL's\n"
    "   * default pixel-center rule — the mappings align directly.            */\n"
    "  vec2 ndc = vec2(a_pos.x / u_fbSize.x * 2.0 - 1.0,\n"
    "                  1.0 - a_pos.y / u_fbSize.y * 2.0);\n"
    "  float w = (a_flags.z != 0) ? a_z : 1.0;   /* persp vs PS1 affine clip */\n"
    "  gl_Position = vec4(ndc, 0.0, w);\n"
    "  v_uv = a_uv;              /* plain: affine when w==1, persp-correct else */\n"
    "  v_colw = a_col * w;       /* affine recovery pair (see header comment)   */\n"
    "  v_ocolw = a_ocol * w;\n"
    "  v_zw = a_z * w;\n"
    "  v_w = w;\n"
    "  v_ddaA = a_ddaA; v_ddaB = a_ddaB; v_ddaAnchor = a_ddaAnchor;\n"
    "  v_texSize = a_texSize; v_flags = a_flags;\n"
    "}\n"
    "\n"
);

/* ============================ FRAGMENT SHADER (GLES) ================== */
static const char* HW_FS_MESH_GLES = (
    "#version 300 es\n"
    "precision highp float;\n"
    "precision highp int;\n"
    "precision highp sampler2DArray;\n"
    "#define RESOLUTION_SCALE 1u\n"
    "/* ShaderGen::WriteHeader's GLSL macro aliases (verbatim set, the subset\n"
    " * the shader references) — these make the VERBATIM shader blocks below\n"
    " * (written in shadergen's api-neutral type style) valid GLSL ES */\n"
    "#define float2 vec2\n"
    "#define float3 vec3\n"
    "#define float4 vec4\n"
    "#define int2 ivec2\n"
    "#define int3 ivec3\n"
    "#define int4 ivec4\n"
    "#define uint2 uvec2\n"
    "#define uint3 uvec3\n"
    "#define uint4 uvec4\n"
    "#define float2x2 mat2\n"
    "#define float3x3 mat3\n"
    "#define float4x4 mat4\n"
    "#define mul(x, y) ((x) * (y))\n"
    "#define nointerpolation flat\n"
    "#define frac fract\n"
    "#define lerp mix\n"
    "#define CONSTANT const\n"
    "#define GLOBAL\n"
    "#define FOR_UNROLL for\n"
    "#define FOR_LOOP for\n"
    "#define IF_BRANCH if\n"
    "#define IF_FLATTEN if\n"
    "uniform sampler2DArray samp0;\n"
    "uniform vec2 u_fbSize;\n"
    "in vec2 v_uv;\n"
    "in vec3 v_colw;\n"
    "in vec3 v_ocolw;\n"
    "in float v_zw;\n"
    "in float v_w;\n"
    "flat in uvec4 v_ddaA;\n"
    "flat in uvec2 v_ddaB;\n"
    "flat in ivec4 v_ddaAnchor;\n"
    "flat in ivec2 v_texSize;\n"
    "flat in ivec4 v_flags;\n"
    "layout(location = 0) out vec4 fragColor;\n"
    "layout(location = 1) out vec4 fragZ;\n"
    "\n"
    "/* ---- 32x32 -> 64 multiply (GLSL ES 3.0 has no int64); two's-complement\n"
    " * bit patterns are identical for signed/unsigned operands -------------- */\n"
    "uvec2 mul_u32(uint a, uint b) {\n"
    "  uint aH = a >> 16u, aL = a & 0xFFFFu;\n"
    "  uint bH = b >> 16u, bL = b & 0xFFFFu;\n"
    "  uint ll = aL * bL;\n"
    "  uint mid = aL * bH + aH * bL;          /* may wrap mod 2^32             */\n"
    "  uint midCarry = (mid < aL * bH) ? 1u : 0u;\n"
    "  uint lo = ll + (mid << 16u);           /* may carry                      */\n"
    "  uint loCarry = (lo < ll) ? 1u : 0u;\n"
    "  uint hi = aH * bH + midCarry + (mid >> 16u) + loCarry;\n"
    "  return uvec2(hi, lo);\n"
    "}\n"
    "/* (hi:lo) >> 12 ARITHMETIC (sign-extended) — the C int64 >> 12          */\n"
    "uvec2 shr_s64_12(uvec2 v) {\n"
    "  uint hi = v.x, lo = v.y;\n"
    "  uint loOut = (hi << 20u) | (lo >> 12u);\n"
    "  uint hiOut = hi >> 12u;\n"
    "  if ((hi & 0x80000000u) != 0u) hiOut |= 0xFFFFE000u;\n"
    "  return uvec2(hiOut, loOut);\n"
    "}\n"
    "uvec2 add64(uvec2 a, uvec2 b) {\n"
    "  uint lo = a.y + b.y;\n"
    "  uint carry = (lo < a.y) ? 1u : 0u;\n"
    "  return uvec2(a.x + b.x + carry, lo);\n"
    "}\n"
    "\n"
    "/* ================== SWANSTATION VERBATIM (gpu_hw_shadergen.cpp) ========\n"
    " * s_dither_values + ApplyDithering, exactly as generated (CONSTANT and the\n"
    " * uint2/uint3 types resolve through the WriteHeader macros above).       */\n"
    "CONSTANT int[16] s_dither_values = int[16]( -4, +0, -3, +1, +2, -2, +3, -1, -3, +1, -4, +0, +3, -1, +2, -2 );\n"
    "\n"
    "uniform uint u_scaled_dithering;\n"
    "uniform uint u_true_color;\n"
    "\n"
    "uint3 ApplyDithering(uint2 coord, uint3 icol)\n"
    "{\n"
    "  uint2 fc;\n"
    "  if (u_scaled_dithering != 0u)\n"
    "    fc = coord & uint2(3u, 3u);\n"
    "  else\n"
    "    fc = (coord / uint2(RESOLUTION_SCALE, RESOLUTION_SCALE)) & uint2(3u, 3u);\n"
    "  int offset = s_dither_values[fc.y * 4u + fc.x];\n"
    "\n"
    "  if (u_true_color != 0u)\n"
    "    return uint3(clamp(int3(icol) + int3(offset, offset, offset), 0, 255));\n"
    "  else\n"
    "    return uint3(clamp((int3(icol) + int3(offset, offset, offset)) >> 3, 0, 31));\n"
    "}\n"
    "/* ================== END SWANSTATION VERBATIM ========================== */\n"
    "\n"
    "/* rgb_to_15bit_expand: the engine's 5->8 replication applied after the\n"
    " * verbatim ApplyDithering — the full chain is fb_put's\n"
    " * expand5(quantize8(c)) == expand5(clamp((c+d)>>3, 0, 31)) (proven equal:\n"
    " * clamp-then-shift and shift-then-clamp agree for all c,d)             */\n"
    "uint expand5(uint v) { return (v << 3u) | (v >> 2u); }\n"
    "\n"
    "void main() {\n"
    "  /* the pixel's INTEGER top-left coordinate — raster_tri's DDA evaluation\n"
    "   * position (DuckStation's integer current_x/current_y, no +0.5).\n"
    "   * GL's framebuffer origin is bottom-left; the engine's is top-left.   */\n"
    "  ivec2 pix = ivec2(int(gl_FragCoord.x), int(u_fbSize.y - gl_FragCoord.y));\n"
    "  if (u_true_color == 7u) { fragColor = vec4(float(v_flags.x)/4.0, float(v_flags.y), float(v_flags.w)/27.0, 1.0); fragZ = vec4(1.0); return; }\n"
    "\n"
    "  /* ---- texture sampling ------------------------------------------------ */\n"
    "  vec4 texel;\n"
    "  if (v_flags.y != 0) {\n"
    "    /* raster_tri's exact sequence (the DuckStation UV DDA). v45 audit\n"
    "     * H-1: the anchor's z,w slots carry the FLOAT BITS of the\n"
    "     * double factor 4096/scale — the multiply runs in float and\n"
    "     * truncates ONCE, the engine's own single-truncation\n"
    "     * arithmetic (the old int32 pre-truncation lost up to\n"
    "     * 0.667 Q12/px from the anchor and drifted the sampled texel\n"
    "     * by up to 0.078 engine px at fractional-scale modes):\n"
    "     *   dxq = (int64)(x * ddaKX) - ddaX0  (x < 320*scale, so\n"
    "     *   x*ddaKX < 320*4096 = 1,310,720: s32-safe at EVERY scale;\n"
    "     *   bit-identical at integral scales, where 4096/scale is an\n"
    "     *   exact power of two and the float product is exact)\n"
    "     *   usum = (int64)U0 + (((int64)(s32)Dudx * dxq) >> 12)\n"
    "     *                       + (((int64)(s32)Dudy * dyq) >> 12)\n"
    "     *   texel = Truncate8(usum >> 24) % tw  (the u8 texcoord wrap)      */\n"
    "    int dxq = int(float(pix.x) * uintBitsToFloat(uint(v_ddaAnchor.z)))\n"
    "             - v_ddaAnchor.x;\n"
    "    int dyq = int(float(pix.y) * uintBitsToFloat(uint(v_ddaAnchor.w)))\n"
    "             - v_ddaAnchor.y;\n"
    "    uvec2 t1 = shr_s64_12(mul_u32(v_ddaA.z, uint(dxq)));\n"
    "    uvec2 t2 = shr_s64_12(mul_u32(v_ddaA.w, uint(dyq)));\n"
    "    uvec2 t3 = shr_s64_12(mul_u32(v_ddaB.x, uint(dxq)));\n"
    "    uvec2 t4 = shr_s64_12(mul_u32(v_ddaB.y, uint(dyq)));\n"
    "    uvec2 usum = add64(add64(uvec2(0u, v_ddaA.x), t1), t2);\n"
    "    uvec2 vsum = add64(add64(uvec2(0u, v_ddaA.y), t3), t4);\n"
    "    uint iu = (usum.y >> 24u) & 0xFFu;   /* Truncate8: the u8 wrap at 256  */\n"
    "    uint iv = (vsum.y >> 24u) & 0xFFu;\n"
    "    int iuw = int(iu) % v_texSize.x; if (iuw < 0) iuw += v_texSize.x;\n"
    "    int ivw = int(iv) % v_texSize.y; if (ivw < 0) ivw += v_texSize.y;\n"
    "    texel = texelFetch(samp0, ivec3(iuw, ivw, v_flags.w), 0);\n"
    "  } else {\n"
    "    /* tex_sample fallback: floorf(u*tw) + modulo wrap — replicated with\n"
    "     * texelFetch + manual wrap (the array's layers are padded, so GL's\n"
    "     * own wrap can never be used)                                        */\n"
    "    int fu = int(floor(v_uv.x * float(v_texSize.x)));\n"
    "    int fv = int(floor(v_uv.y * float(v_texSize.y)));\n"
    "    fu %= v_texSize.x; if (fu < 0) fu += v_texSize.x;\n"
    "    fv %= v_texSize.y; if (fv < 0) fv += v_texSize.y;\n"
    "    texel = texelFetch(samp0, ivec3(fu, fv, v_flags.w), 0);\n"
    "  }\n"
    "\n"
    "  uint ta = uint(texel.a * 255.0 + 0.5);\n"
    "  if (ta == 0u) discard;   /* PSX 0x0000 hole (DuckStation: texture_color==0 -> return) */\n"
    "\n"
    "  /* the per-vertex colors: affine recovery (w==1 in PS1 mode -> the plain\n"
    "   * varying); the CPU rounds with (int)(x + 0.5) — replicated exactly  */\n"
    "  vec3 vcol = v_colw / v_w;   /* w10: DIVIDE — the perspective-correct varying recovery */\n"
    "  vec3 vocol = v_ocolw / v_w; /* w10: same */\n"
    "  int vr = int(vcol.r + 0.5);\n"
    "  int vg = int(vcol.g + 0.5);\n"
    "  int vb = int(vcol.b + 0.5);\n"
    "  int orr = int(vocol.r + 0.5);\n"
    "  int og = int(vocol.g + 0.5);\n"
    "  int ob = int(vocol.b + 0.5);\n"
    "  int tr = int(texel.r * 255.0 + 0.5);\n"
    "  int tg = int(texel.g * 255.0 + 0.5);\n"
    "  int tb = int(texel.b * 255.0 + 0.5);\n"
    "\n"
    "  /* engine modulate + additive veil (raster_tri's SwanStation form:\n"
    "   * ((texel5 * color8) >> 4) + veil — then fb_put quantizes)            */\n"
    "  int r = (((tr >> 3) * vr) >> 4) + orr;\n"
    "  int g = (((tg >> 3) * vg) >> 4) + og;\n"
    "  int b = (((tb >> 3) * vb) >> 4) + ob;\n"
    "\n"
    "  /* fb_put(quantize, dither): mode = dither | quantize<<1\n"
    "   *   quantize && dither : expand5(ApplyDithering(c))      (15-bit + dith)\n"
    "   *   quantize only      : expand5(clamp(c) >> 3)          (15-bit)\n"
    "   *   neither            : clamp(c)                        (24-bit)\n"
    "   * v10.2 AUDIT FIX (fb_put branch): the CPU's fb_put gates on\n"
    "   * QUANTIZE alone (`if (quantize)`) — dither is INERT when\n"
    "   * quantize == 0, so (q=0, d=1) renders the plain 24-bit clamp.\n"
    "   * The v9.9-v10.1 code branched on `v_flags.x != 0`, wrongly\n"
    "   * dithering that case (a real HW/SW divergence in --modern +\n"
    "   * dither-on). The outer branch now tests the quantize bit\n"
    "   * (bit 1), exactly like fb_put.                                  */\n"
    "  if ((v_flags.x & 2) != 0) {\n"
    "    if ((v_flags.x & 1) != 0) {\n"
    "      uint3 d = ApplyDithering(uint2(pix), uint3(clamp(ivec3(r, g, b), 0, 255)));\n"
    "      fragColor = vec4(float(expand5(d.x)) / 255.0,\n"
    "                       float(expand5(d.y)) / 255.0,\n"
    "                       float(expand5(d.z)) / 255.0, 1.0);\n"
    "    } else {\n"
    "      uint3 c5 = uint3(clamp(ivec3(r, g, b), 0, 255)) >> 3u;\n"
    "      fragColor = vec4(float(expand5(c5.x)) / 255.0,\n"
    "                       float(expand5(c5.y)) / 255.0,\n"
    "                       float(expand5(c5.z)) / 255.0, 1.0);\n"
    "    }\n"
    "  } else {\n"
    "    fragColor = vec4(float(clamp(r, 0, 255)) / 255.0,\n"
    "                     float(clamp(g, 0, 255)) / 255.0,\n"
    "                     float(clamp(b, 0, 255)) / 255.0, 1.0);\n"
    "  }\n"
    "  /* the flake-occlusion depth (affine z == raster_tri's barycentric z) */\n"
    "  fragZ = vec4(v_zw / v_w, 0.0, 0.0, 1.0);  /* w10: same */\n"
    "}\n"
    "\n"
);

#endif /* SH1_HW_SHADERS_H */
